"""Framework for connecting AI-generated scene instructions to the engine."""

from __future__ import annotations

import json
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import TYPE_CHECKING, Any, Protocol, cast

from .animation import Animation
from .objects import BaseObject
from .scene import Scene

if TYPE_CHECKING:
    from .renderer import SVGRenderer


class AIModelClient(Protocol):
    """Protocol for any external AI model adapter."""

    def generate(self, prompt: str) -> str:
        """Return a JSON string describing a scene plan."""


@dataclass(frozen=True, slots=True)
class AIActionSpec:
    """One action generated by the AI."""

    object: str
    action: str
    parameters: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True, slots=True)
class AIPlan:
    """Parsed AI output for a scene and its actions."""

    scene: str
    actions: list[AIActionSpec]

    @classmethod
    def from_mapping(cls, payload: Mapping[str, Any]) -> "AIPlan":
        """Create a plan from a decoded mapping."""
        scene = payload.get("scene")
        actions = payload.get("actions", [])
        if not isinstance(scene, str) or not scene:
            raise ValueError("AI plan must include a non-empty scene name.")
        if not isinstance(actions, list):
            raise ValueError("AI plan actions must be a list.")

        parsed_actions: list[AIActionSpec] = []
        for action in actions:
            if not isinstance(action, Mapping):
                raise ValueError("Each AI action must be an object.")
            object_name = action.get("object")
            action_name = action.get("action")
            parameters = action.get("parameters", {})
            if not isinstance(object_name, str) or not object_name:
                raise ValueError("Each AI action needs an object name.")
            if not isinstance(action_name, str) or not action_name:
                raise ValueError("Each AI action needs an action name.")
            if not isinstance(parameters, Mapping):
                raise ValueError("AI action parameters must be a mapping.")
            parsed_actions.append(
                AIActionSpec(
                    object=object_name,
                    action=action_name,
                    parameters=dict(parameters),
                )
            )
        return cls(scene=scene, actions=parsed_actions)

    @classmethod
    def from_json(cls, payload: str) -> "AIPlan":
        """Create a plan from JSON text."""
        return cls.from_mapping(json.loads(payload))


AIActionHandler = Callable[[Scene, BaseObject, Mapping[str, Any]], Animation | Sequence[Animation] | None]
SceneFactory = Callable[[], Scene]


@dataclass
class SceneRegistry:
    """Registry for scene templates referenced by AI plans."""

    factories: dict[str, SceneFactory] = field(default_factory=dict)

    def register(self, name: str, factory: SceneFactory) -> SceneFactory:
        """Register a scene factory."""
        self.factories[name] = factory
        return factory

    def build(self, name: str) -> Scene:
        """Build a scene by name."""
        try:
            return self.factories[name]()
        except KeyError as exc:
            raise KeyError(f"Unknown scene '{name}'.") from exc


@dataclass
class ActionRegistry:
    """Registry for AI action handlers."""

    handlers: dict[str, AIActionHandler] = field(default_factory=dict)

    def register(self, name: str, handler: AIActionHandler) -> AIActionHandler:
        """Register an action handler."""
        self.handlers[name] = handler
        return handler

    def apply(self, scene: Scene, action: AIActionSpec) -> None:
        """Apply an AI action to a scene object."""
        try:
            handler = self.handlers[action.action]
        except KeyError as exc:
            raise KeyError(f"Unknown action '{action.action}'.") from exc
        target = scene.object(action.object)
        handler(scene, target, action.parameters)


def register_default_action_handlers(registry: ActionRegistry) -> ActionRegistry:
    """Register action handlers for built-in composite objects."""

    def _walk(scene: Scene, target: BaseObject, parameters: Mapping[str, Any]) -> None:
        duration = float(parameters.get("duration", 2.0))
        distance = float(parameters.get("distance", 160.0))
        easing = str(parameters.get("easing", "ease-in-out"))
        walk = getattr(target, "walk", None)
        if not callable(walk):
            raise TypeError("Target object does not support walk().")
        walk_callable = cast(Callable[..., Any], walk)
        walk_callable(scene.animation_manager, duration=duration, distance=distance, easing=easing)

    def _point(scene: Scene, target: BaseObject, parameters: Mapping[str, Any]) -> None:
        duration = float(parameters.get("duration", 1.0))
        arm = str(parameters.get("arm", "right"))
        easing = str(parameters.get("easing", "ease-out"))
        point = getattr(target, "point", None)
        if not callable(point):
            raise TypeError("Target object does not support point().")
        point_callable = cast(Callable[..., Any], point)
        point_callable(scene.animation_manager, duration=duration, arm=arm, easing=easing)

    def _wave(scene: Scene, target: BaseObject, parameters: Mapping[str, Any]) -> None:
        duration = float(parameters.get("duration", 1.0))
        arm = str(parameters.get("arm", "right"))
        easing = str(parameters.get("easing", "ease-in-out"))
        wave = getattr(target, "wave", None)
        if not callable(wave):
            raise TypeError("Target object does not support wave().")
        wave_callable = cast(Callable[..., Any], wave)
        wave_callable(scene.animation_manager, duration=duration, arm=arm, easing=easing)

    registry.register("walk", _walk)
    registry.register("point", _point)
    registry.register("wave", _wave)
    return registry


@dataclass
class AIEngine:
    """Connect an AI model client to scene execution."""

    renderer: SVGRenderer
    scene_registry: SceneRegistry = field(default_factory=SceneRegistry)
    action_registry: ActionRegistry = field(default_factory=ActionRegistry)
    model_client: AIModelClient | None = None

    def request_plan(self, prompt: str) -> AIPlan:
        """Ask the configured AI client for a plan."""
        if self.model_client is None:
            raise RuntimeError("No AI model client has been configured.")
        return AIPlan.from_json(self.model_client.generate(prompt))

    def build_scene(self, plan: AIPlan) -> Scene:
        """Build the scene described by an AI plan."""
        scene = self.scene_registry.build(plan.scene)
        for action in plan.actions:
            self.action_registry.apply(scene, action)
        return scene

    def execute_plan(self, plan: AIPlan, output_path: str | Path, duration: float) -> Path:
        """Execute a parsed plan and export the result."""
        scene = self.build_scene(plan)
        return self.renderer.export_scene_mp4(output_path, scene, duration)

    def execute_prompt(self, prompt: str, output_path: str | Path, duration: float) -> Path:
        """Generate a plan from the AI client and execute it."""
        return self.execute_plan(self.request_plan(prompt), output_path, duration)
